CREATE TABLE subscription_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL,
    max_active_offers INT NOT NULL DEFAULT 0,
    max_open_requests INT NOT NULL DEFAULT 0,
    base_visibility_score INT NOT NULL DEFAULT 0,
    can_create BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_subscription_plan_name UNIQUE (name)
);

CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(10) NOT NULL,
    company_name VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    validated BOOLEAN NOT NULL DEFAULT FALSE,
    suspended BOOLEAN NOT NULL DEFAULT FALSE,
    reliability_score INT NOT NULL DEFAULT 50,
    subscription_plan_id BIGINT REFERENCES subscription_plan(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_account_email UNIQUE (email)
);

CREATE TABLE offer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES user_account(id),
    resource_type VARCHAR(20) NOT NULL DEFAULT 'TRANSPORT',
    start_datetime TIMESTAMP NOT NULL,
    end_datetime TIMESTAMP NOT NULL,
    quantity_available INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE offer_transport_detail (
    offer_id BIGINT PRIMARY KEY REFERENCES offer(id),
    vehicle_category VARCHAR(50),
    max_load_tons DECIMAL(10,2),
    volume_m3 DECIMAL(10,2),
    length_m DECIMAL(10,2),
    with_driver BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE transport_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES user_account(id),
    resource_type VARCHAR(20) NOT NULL DEFAULT 'TRANSPORT',
    start_datetime TIMESTAMP NOT NULL,
    end_datetime TIMESTAMP NOT NULL,
    quantity_max INT NOT NULL,
    quantity_committed INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE request_transport_detail (
    request_id BIGINT PRIMARY KEY REFERENCES transport_request(id),
    required_vehicle_category VARCHAR(50),
    min_load_tons DECIMAL(10,2),
    with_driver BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE commitment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES transport_request(id),
    offer_id BIGINT NOT NULL REFERENCES offer(id),
    quantity INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ENGAGED',
    cancel_reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES user_account(id),
    target_user_id BIGINT NOT NULL REFERENCES user_account(id),
    action_type VARCHAR(50) NOT NULL,
    reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
